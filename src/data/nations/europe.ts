type P = [string,string,number,'GK'|'CB'|'LB'|'RB'|'LWB'|'RWB'|'CDM'|'CM'|'CAM'|'LM'|'RM'|'LW'|'RW'|'CF'|'ST',number,string,'star'|'solid'|'fringe',boolean?];
type Groups = [string, string, string, string];

function p(rows:P[]) {
  return rows.map(([name,nameEn,number,position,age,club,tier,isCaptain])=>({name,nameEn,number,position,age,club,tier,isCaptain}));
}

const groupPositions: P[3][][] = [
  ['GK', 'GK'],
  ['RB', 'CB', 'CB', 'CB', 'LB', 'LB'],
  ['CDM', 'CM', 'CM', 'CAM', 'RM', 'LM'],
  ['RW', 'ST', 'ST', 'LW', 'CF', 'RW'],
];

function squad(groups: Groups) {
  let number = 0;
  return groups.flatMap((group, groupIndex) =>
    group.split(',').map((entry, index) => {
      number += 1;
      const captain = entry.startsWith('*');
      const [name, nameEn = name] = (captain ? entry.slice(1) : entry).split('/');
      return {
        name, nameEn, number, position: groupPositions[groupIndex][index],
        age: 21 + ((number * 7 + nameEn.length) % 13), club: '국가대표팀',
        tier: (number <= 3 || captain ? 'star' : number <= 16 ? 'solid' : 'fringe') as 'star'|'solid'|'fringe',
        isCaptain: captain || undefined,
      };
    }),
  );
}

